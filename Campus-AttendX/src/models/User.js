const mongoose = require("mongoose");
const { Schema } = mongoose;

const userSchema = new Schema(
    {
        firstName: { type: String, minlength: 3, maxlength: 20, required: true, trim: true },
        lastName: { type: String, required: true, trim: true, maxlength: 50 },
        emailId: { type: String, required: true, lowercase: true, trim: true, unique: true, index: true },
        password: { type: String, required: true },
        phone: { type: String, unique: true, required: true, trim: true },

        role: {
            type: String,
            required: true,
            enum: ["student", "faculty", "admin"],
            default: "student",
            index: true
        },

        registrationNumber: {
            type: String,
            trim: true,
            unique: true,
            sparse: true,
            required: function () { return this.role === "student"; }
        },

        department: {
            type: String,
            required: function () {
                return this.role === "student" || this.role === "faculty";
            },
            enum: ["SFET"],
            trim: true,
            uppercase: true
        },

        course: {
            type: String,
            required: function () {
                return this.role === "student" || this.role === "faculty";
            },
            enum: ["B.TECH", "BCA", "DIPLOMA"],
            uppercase: true,
            trim: true
        },

        branch: {
            type: String,
            required: function () {
                return this.role === "student" || this.role === "faculty";
            },
            enum: ["CE", "AI/ML", "ECE", "ME"],
            uppercase: true,
            trim: true
        },

        adminBranch: {
            type: String,
            enum: ["ALL", "CE", "AI/ML", "ECE", "ME", "BCA", "DIPLOMA CE"],
            default: "ALL",
            required: function () { return this.role === "admin"; },
            uppercase: true,
            trim: true
        },

        batch: {
            type: Number,
            required: function () { return this.role === "student"; },
            min: 2000,
            max: 2100,
            index: true
        },

        semester: {
            type: Number,
            min: 1,
            max: 8,
            required: function () { return this.role === "student"; }
        },

        isActive: { type: Boolean, default: true },

        profileImage: { type: String, default: null },

        lastLogin: { type: Date, default: null },

        // ============================================================
        // DEVICE BINDING (used by 4-step attendance flow)
        //
        // - deviceId: random UUID generated by the client
        // - deviceKey: 256-bit secret held ONLY by the client; server
        //   stores it (select:false) to verify HMAC proofs
        // - boundAt: timestamp of last binding
        // ============================================================
        deviceBinding: {
            deviceId: { type: String, default: null, index: true },
            deviceKey: { type: String, default: null, select: false },
            boundAt: { type: Date, default: null }
        }
    },
    { timestamps: true }
);

userSchema.index({
    department: 1,
    branch: 1,
    batch: 1,
    semester: 1
});

const User = mongoose.model("User", userSchema);
module.exports = User;